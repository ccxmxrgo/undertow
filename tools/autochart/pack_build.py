"""Autocharter pack assembler (Phase 2.2.2 plan 06; D-03, D-04, D-08, D-15, D-16).

Runs after build_pack.ps1 has put the standalone interpreter (+ hash-locked wheels) into <stage>/rt and the
models into <stage>/models. This script then:

  prune        drop dev-only parts of the runtime (tests, headers, import libs, pip, tk, __pycache__);
               licence files (LICENSE*, NOTICE*, COPYING*, *.dist-info/**) are never removed
  app          copy the pack entry points (allow-list of .py files) into <stage>/app and the licence
               summary into <stage>/NOTICES (+ NOTICES/INDEX.txt listing every licence file in the runtime)
  parts        assign every file to a part (app, rt-core, rt-torch, models[, rt310]); a part over
               MAX_PART_ENTRIES files is split alphabetically into -a/-b/... parts with the same roots
  zips         deterministic zips: sorted entries, forward slashes, fixed 1980-01-01 time and attributes,
               ZIP_DEFLATED level 6, no Zip64 (oversize fails loudly), no audio entries (D-08)
  pins         SHA256SUMS.txt, pack_manifest.json and the game's src/autocharter/pack_spec.gd (PackSpec)

STANDARD LIBRARY ONLY. Run with any Python 3.12 as `python -I -B pack_build.py ...`.

  pack_build.py --stage build/pack/stage --out build/pack/out --spec src/autocharter/pack_spec.gd
                [--app-only] [--interpreters 1|2]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import shutil
import stat
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]

VERSION = 1
TAG = "autocharter-pack-v%d" % VERSION
BASE_URL = "https://github.com/ccxmxrgo/Undertow-autocharter/releases/download/%s/" % TAG
PART_PREFIX = "undertow-ac-v%d-" % VERSION

# One constant for both the zip writer and the split (below PackExtractor.MAX_ENTRIES = 60000).
MAX_PART_ENTRIES = 55000

AUDIO_SUFFIXES = (".mp3", ".ogg", ".wav", ".flac", ".opus", ".m4a")
ZIP_DATE = (1980, 1, 1, 0, 0, 0)
ZIP_LEVEL = 6
ZIP_ATTR = (stat.S_IFREG | 0o644) << 16
CHUNK = 1 << 20

# site-packages top-level names (normalised) that go to the rt-torch part, with their *.dist-info.
TORCH_SET = frozenset({
    "torch", "torchaudio", "torchgen", "functorch", "demucs", "beat_this", "einops", "rotary_embedding_torch",
    "julius", "sympy", "mpmath", "networkx", "huggingface_hub", "openunmix", "dora", "lameenc",
})
# distribution names whose import package has another name
DIST_ALIASES = {"dora_search": "dora"}

PART_ORDER = ("app", "rt-core", "rt-torch", "models", "rt310")
PART_ROOTS = {"app": ["app", "NOTICES"], "rt-core": ["rt"], "rt-torch": ["rt"], "models": ["models"],
              "rt310": ["rt310"]}

# runtime paths removed by prune (relative to the interpreter root). Scripts/ holds the console entry
# points uv generated; they embed the absolute build path of python.exe (useless and a path leak).
PRUNE_DIRS = ("Lib/test", "Lib/idlelib", "Lib/tkinter", "Lib/turtledemo", "tcl", "Scripts",
              "Lib/site-packages/torch/include", "Lib/site-packages/torch/testing/_internal/data")
LICENCE_PREFIXES = ("license", "licence", "notice", "copying")

# app allow-list (never tests/, reports/, *.ps1, note_sync.py, mid_notes.py, dump_chart_times.gd)
APP_FILES = ("autochart.py", "stem_rank.py", "bp_worker.py")
APP_DIRS = ("stages",)

SPEC_HEAD = '''class_name PackSpec
extends RefCounted
## GENERATED by tools/autochart/pack_build.py from the built pack parts. Do not hand-edit; rebuild the pack instead.
## Pinned Autocharter pack parts (D-04). The installer trusts ONLY these sizes and SHA-256
## values, which are compiled into the game; no manifest is ever downloaded.

'''

SPEC_TAIL = '''

static func available() -> bool:
	return not PARTS.is_empty()


static func download_bytes() -> int:
	var total := 0
	for p in PARTS:
		total += int(p["size"])
	return total


static func url(part: Dictionary) -> String:
	return BASE_URL + String(part["name"])


static func as_dict() -> Dictionary:
	return {
		"version": VERSION,
		"tag": TAG,
		"base_url": BASE_URL,
		"parts": PARTS.duplicate(true),
		"unpacked_bytes": UNPACKED_BYTES,
	}
'''


# ---------------------------------------------------------------- prune

def is_licence_file(name: str) -> bool:
    return name.lower().startswith(LICENCE_PREFIXES)


def _rm_tree_keep_licences(d: Path) -> int:
    """Remove d except licence files (and the dirs that hold them). Returns files removed."""
    removed = 0
    for cur, dirs, files in os.walk(d, topdown=False):
        for f in files:
            if not is_licence_file(f):
                os.remove(os.path.join(cur, f))
                removed += 1
        try:
            os.rmdir(cur)
        except OSError:
            pass  # still holds a licence file
    return removed


def _rm_tree(d: Path) -> int:
    n = sum(len(files) for _, _, files in os.walk(d))
    shutil.rmtree(d)
    return n


def prune(rt: Path) -> int:
    """Prune an interpreter root in place (assumption A7: the extracted-pack selftest proves it safe)."""
    rt = Path(rt)
    removed = 0
    for rel in PRUNE_DIRS:
        p = rt / rel
        if p.is_dir():
            removed += _rm_tree_keep_licences(p)
    sp = rt / "Lib" / "site-packages"
    if sp.is_dir():
        for child in sorted(sp.iterdir()):
            low = child.name.lower()
            if low == "pip" or low.startswith("pip-"):
                removed += _rm_tree(child) if child.is_dir() else (child.unlink() or 1)
        torch_dir = sp / "torch"
        if torch_dir.is_dir():
            for cur, _dirs, files in os.walk(torch_dir):
                for f in files:
                    if f.lower().endswith(".lib"):
                        os.remove(os.path.join(cur, f))
                        removed += 1
        # tests / test folders inside packages (never inside *.dist-info)
        for cur, dirs, _files in os.walk(sp, topdown=True):
            rel_parts = Path(cur).relative_to(sp).parts
            if any(part.endswith(".dist-info") for part in rel_parts):
                dirs[:] = []
                continue
            keep = []
            for d in sorted(dirs):
                if d.endswith(".dist-info"):
                    continue
                if d in ("tests", "test") and rel_parts:
                    removed += _rm_tree_keep_licences(Path(cur) / d)
                    if (Path(cur) / d).exists():
                        keep.append(d)
                else:
                    keep.append(d)
            dirs[:] = keep
    for cur, dirs, _files in os.walk(rt, topdown=True):
        if "__pycache__" in dirs:
            removed += _rm_tree(Path(cur) / "__pycache__")
            dirs.remove("__pycache__")
    return removed


# ---------------------------------------------------------------- parts

def _norm(name: str) -> str:
    return name.lower().replace("-", "_").replace(".", "_")


def site_top_name(entry: str) -> str:
    """Normalised import/distribution name of a site-packages top-level entry."""
    if entry.endswith(".dist-info") or entry.endswith(".data"):
        base = entry.rsplit(".", 1)[0].split("-", 1)[0]
        n = _norm(base)
        return DIST_ALIASES.get(n, n)
    if entry.endswith(".libs"):
        return _norm(entry[:-5])
    base = entry.split(".", 1)[0]  # foo.py, foo.cp312-win_amd64.pyd, foo.pth
    return _norm(base)


def assign_part(rel: str) -> str:
    parts = rel.replace("\\", "/").split("/")
    top = parts[0]
    if top in ("app", "NOTICES"):
        return "app"
    if top == "models":
        return "models"
    if top == "rt310":
        return "rt310"
    if top == "rt":
        if len(parts) >= 4 and parts[1] == "Lib" and parts[2] == "site-packages":
            if site_top_name(parts[3]) in TORCH_SET:
                return "rt-torch"
        return "rt-core"
    raise ValueError("file outside the pack roots: %s" % rel)


def base_part(part: str) -> str:
    for b in PART_ORDER:
        if part == b or (part.startswith(b + "-") and len(part) == len(b) + 2 and part[-1].isalpha()):
            return b
    raise ValueError("unknown part %s" % part)


def part_roots(part: str) -> list:
    return list(PART_ROOTS[base_part(part)])


def split_groups(groups: dict) -> dict:
    """Split any part over MAX_PART_ENTRIES alphabetically into -a/-b/... parts (same roots)."""
    out = {}
    for part, rels in groups.items():
        rels = sorted(rels)
        if len(rels) <= MAX_PART_ENTRIES:
            out[part] = rels
            continue
        n = math.ceil(len(rels) / MAX_PART_ENTRIES)
        size = math.ceil(len(rels) / n)
        for i in range(n):
            out["%s-%s" % (part, "abcdefghijklmnopqrstuvwxyz"[i])] = rels[i * size:(i + 1) * size]
    return out


def part_sort_key(part: str):
    return (PART_ORDER.index(base_part(part)), part)


def part_file_name(part: str) -> str:
    return "%s%s.zip" % (PART_PREFIX, part)


# ---------------------------------------------------------------- zips / hashes

def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(CHUNK)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def write_zip(zip_path: Path, root: Path, rels) -> int:
    """Deterministic part zip of root/<rel> for every rel. Returns the entry count."""
    names = sorted({r.replace("\\", "/") for r in rels})
    if len(rels) > MAX_PART_ENTRIES or len(names) > MAX_PART_ENTRIES:
        raise ValueError("%s: %d entries > MAX_PART_ENTRIES %d" % (zip_path, len(rels), MAX_PART_ENTRIES))
    for n in names:
        if n.lower().endswith(AUDIO_SUFFIXES):
            raise ValueError("audio file in pack (D-08): %s" % n)
        if n.startswith("/") or ".." in n.split("/") or ":" in n:
            raise ValueError("unsafe entry name: %s" % n)
    zip_path = Path(zip_path)
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    tmp = zip_path.with_name(zip_path.name + ".tmp")
    with zipfile.ZipFile(tmp, "w", compression=zipfile.ZIP_DEFLATED, allowZip64=False) as zf:
        for n in names:
            info = zipfile.ZipInfo(n, date_time=ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 0
            info.external_attr = ZIP_ATTR
            data = (Path(root) / n).read_bytes()
            zf.writestr(info, data, compress_type=zipfile.ZIP_DEFLATED, compresslevel=ZIP_LEVEL)
    os.replace(tmp, zip_path)
    return len(names)


def sha256sums_text(parts) -> str:
    return "".join("%s  %s\n" % (p["sha256"], p["name"]) for p in sorted(parts, key=lambda p: p["name"]))


def render_spec(parts, unpacked: int) -> str:
    if parts:
        rows = []
        for p in parts:
            roots = ", ".join('"%s"' % r for r in p["roots"])
            rows.append('\t{"name": "%s", "size": %d, "sha256": "%s", "roots": [%s]},'
                        % (p["name"], int(p["size"]), p["sha256"], roots))
        parts_txt = "[\n" + "\n".join(rows) + "\n]"
    else:
        parts_txt = "[]"
    body = ('const VERSION := %d\nconst TAG := "%s"\nconst BASE_URL := "%s"\n'
            "const PARTS: Array[Dictionary] = %s\nconst UNPACKED_BYTES := %d\n"
            % (VERSION, TAG, BASE_URL, parts_txt, int(unpacked)))
    return SPEC_HEAD + body + SPEC_TAIL


# ---------------------------------------------------------------- staging

def copy_text(src: Path, dst: Path) -> None:
    """Copy a text file with LF line endings, so the app part does not depend on git's autocrlf (D-16)."""
    dst.write_bytes(src.read_bytes().replace(b"\r\n", b"\n"))


def stage_app(stage: Path, src: Path = HERE) -> None:
    app = stage / "app"
    if app.exists():
        shutil.rmtree(app)
    app.mkdir(parents=True)
    for f in APP_FILES:
        copy_text(src / f, app / f)
    for d in APP_DIRS:
        (app / d).mkdir()
        for p in sorted((src / d).iterdir()):
            if p.is_file() and p.suffix == ".py":
                copy_text(p, app / d / p.name)


def licence_index(stage: Path) -> list:
    out = []
    for top in ("rt", "rt310"):
        base = stage / top
        if not base.is_dir():
            continue
        for cur, _dirs, files in os.walk(base):
            in_licences = "/licenses" in Path(cur).as_posix() and ".dist-info" in Path(cur).as_posix()
            for f in files:
                if in_licences or is_licence_file(f):
                    out.append((Path(cur) / f).relative_to(stage).as_posix())
    return sorted(out)


def stage_notices(stage: Path, src: Path = HERE / "NOTICES") -> None:
    dst = stage / "NOTICES"
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)
    for p in sorted(src.iterdir()):
        if p.is_file():
            copy_text(p, dst / p.name)
    idx = licence_index(stage)
    text = ("Licence files shipped inside this pack (paths relative to the pack version folder).\n"
            "They stay next to the components they cover.\n\n" + "".join(p + "\n" for p in idx))
    (dst / "INDEX.txt").write_bytes(text.encode("utf-8"))


def collect(stage: Path, tops) -> list:
    out = []
    for top in tops:
        base = stage / top
        if not base.is_dir():
            continue
        for cur, dirs, files in os.walk(base):
            dirs.sort()
            for f in files:
                out.append((Path(cur) / f).relative_to(stage).as_posix())
    return sorted(out)


def unpacked_size(stage: Path, rels) -> int:
    return sum((stage / r).stat().st_size for r in rels)


def build_parts(stage: Path, out: Path, groups: dict) -> list:
    parts = []
    for part in sorted(groups, key=part_sort_key):
        rels = groups[part]
        name = part_file_name(part)
        zp = out / name
        n = write_zip(zp, stage, rels)
        parts.append({"name": name, "size": zp.stat().st_size, "sha256": sha256_file(zp),
                      "roots": part_roots(part), "part": part, "files": n,
                      "unpacked": unpacked_size(stage, rels)})
    return parts


def write_outputs(out: Path, spec: Path, parts: list, interpreters: int) -> int:
    unpacked = sum(p["unpacked"] for p in parts)
    (out / "SHA256SUMS.txt").write_bytes(sha256sums_text(parts).encode("ascii"))
    manifest = {"version": VERSION, "tag": TAG, "interpreters": interpreters, "unpacked_bytes": unpacked,
                "parts": parts, "file_counts": {p["part"]: p["files"] for p in parts}}
    (out / "pack_manifest.json").write_bytes((json.dumps(manifest, indent=1, sort_keys=True) + "\n").encode("ascii"))
    spec_parts = [{k: p[k] for k in ("name", "size", "sha256", "roots")} for p in parts]
    if spec is not None:
        spec.write_bytes(render_spec(spec_parts, unpacked).encode("ascii"))
    return unpacked


def report(parts: list, unpacked: int) -> None:
    total = sum(p["size"] for p in parts)
    for p in parts:
        print("  %-32s %9.1f MB  %6d files  %s" % (p["name"], p["size"] / 1e6, p["files"], p["sha256"]))
    print("PACK_PARTS_OK total %.1f MB (unpacked %.1f MB)" % (total / 1e6, unpacked / 1e6))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--stage", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--spec", type=Path, default=None, help="write the PackSpec here (omit: do not touch)")
    ap.add_argument("--app-only", action="store_true")
    ap.add_argument("--interpreters", type=int, choices=(1, 2), default=1)
    a = ap.parse_args(argv)
    stage, out = a.stage.resolve(), a.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    if a.app_only:
        mpath = out / "pack_manifest.json"
        if not mpath.is_file():
            print("pack_build: --app-only needs %s from a full build" % mpath, file=sys.stderr)
            return 2
        manifest = json.loads(mpath.read_text(encoding="ascii"))
        stage_app(stage)
        stage_notices(stage)
        groups = split_groups({"app": collect(stage, ("app", "NOTICES"))})
        new = build_parts(stage, out, groups)
        keep = [p for p in manifest["parts"] if base_part(p["part"]) != "app"]
        parts = sorted(keep + new, key=lambda p: part_sort_key(p["part"]))
        unpacked = write_outputs(out, a.spec, parts, manifest["interpreters"])
        report(parts, unpacked)
        return 0
    tops = ["rt"] + (["rt310"] if a.interpreters == 2 else [])
    for t in tops:
        if not (stage / t / "python.exe").is_file():
            print("pack_build: %s/python.exe missing" % (stage / t), file=sys.stderr)
            return 2
    if not (stage / "models").is_dir():
        print("pack_build: %s missing" % (stage / "models"), file=sys.stderr)
        return 2
    for t in tops:
        n = prune(stage / t)
        print("pruned %d files from %s" % (n, t))
    stage_app(stage)
    stage_notices(stage)
    for z in out.glob(PART_PREFIX + "*.zip"):
        z.unlink()
    groups = {}
    for rel in collect(stage, ["app", "NOTICES", "models"] + tops):
        groups.setdefault(assign_part(rel), []).append(rel)
    parts = build_parts(stage, out, split_groups(groups))
    unpacked = write_outputs(out, a.spec, parts, a.interpreters)
    report(parts, unpacked)
    return 0


if __name__ == "__main__":
    sys.exit(main())
